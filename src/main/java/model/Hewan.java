package model;

public class Hewan {
    public int idHewan;
    public String namaHewan;
    public String jenisHewan;
    
    public Hewan(){
    }
    
    public Hewan(int idHewan, String namaHewan, String jenisHewan){
            this.idHewan = idHewan;
            this.namaHewan = namaHewan;
            this.jenisHewan = jenisHewan;
    }
}
    
